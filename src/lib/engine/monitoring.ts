const round = (n: number, d = 1) => Math.round(n * 10 ** d) / 10 ** d;

function trend(
  id: string,
  label: string,
  unit: string,
  visits: MonitoringVisit[],
  pick: (v: MonitoringVisit) => number | null,
): MonitoringTrend {
  const points = visits
    .map((v) => ({ day: v.day, value: pick(v) }))
    .filter((p): p is { day: number; value: number } => p.value !== null);

  if (points.length === 0) {
    return {
      id,
      label,
      latest: "Not recorded",
      previous: "Not recorded",
      change: "—",
      perDay: "—",
      direction: "unknown",
    };
  }
  const last = points[points.length - 1]!;
  if (points.length === 1) {
    return {
      id,
      label,
      latest: `${last.value} ${unit}`.trim(),
      previous: "No earlier measurement",
      change: "—",
      perDay: "—",
      direction: "unknown",
    };
  }
  const prev = points[points.length - 2]!;
  const delta = round(last.value - prev.value, 2);
  const days = Math.max(1, last.day - prev.day);
  const perDay = round(delta / days, 2);
  return {
    id,
    label,
    latest: `${last.value} ${unit}`.trim(),
    previous: `${prev.value} ${unit} (day ${prev.day})`.trim(),
    change: `${delta > 0 ? "+" : ""}${delta} ${unit}`.trim(),
    perDay: `${perDay > 0 ? "+" : ""}${perDay} ${unit}/day`.trim(),
    direction: delta > 0 ? "rising" : delta < 0 ? "falling" : "stable",
  };
}

export function analyzeMonitoring(
  context: MonitoringContext,
  rawVisits: MonitoringVisit[],
): MonitoringResult {
  const visits = rawVisits.map(normalizeVisit).sort((a, b) => a.day - b.day);

  const series: MonitoringSeriesPoint[] = visits.map((v) => ({
    day: v.day,
    largestFollicle: v.largestFollicle,
    follicles10: v.follicles10,
    follicles14: v.follicles14,
    follicles17: v.follicles17,
    follicleCount: v.follicleCount,
    estradiol: v.estradiol,
    endometrium: v.endometrium,
    dailyDose: v.dailyDose,
    progesterone: v.progesterone,
    lh: v.lh,
  }));

  const trends: MonitoringTrend[] = [
    trend("largest", "Largest follicle", "mm", visits, (v) => v.largestFollicle),
    trend("f10", "Follicles ≥ 10 mm", "", visits, (v) => v.follicles10),
    trend("f14", "Follicles ≥ 14 mm", "", visits, (v) => v.follicles14),
    trend("f17", "Follicles ≥ 17 mm", "", visits, (v) => v.follicles17),
    trend("e2", "Estradiol", "pg/mL", visits, (v) => v.estradiol),
    trend("endometrium", "Endometrial thickness", "mm", visits, (v) => v.endometrium),
    trend("dose", "Daily dose", "IU", visits, (v) => v.dailyDose),
    trend("p4", "Progesterone", "ng/mL", visits, (v) => v.progesterone),
    trend("lh", "LH", "IU/L", visits, (v) => v.lh),
  ];

  /* ------------------------------------------------------- completeness */

  const coreFields = monitoringFields.filter((f) => f.core);
  const missingByVisit = visits.map((v) => ({
    day: v.day,
    missing: coreFields
      .filter((f) => {
        const value = v[f.key];
        return value === null || value === undefined || value === "";
      })
      .map((f) => f.label),
  }));
  const expectedFields = visits.length * coreFields.length;
  const recordedFields = expectedFields - missingByVisit.reduce((s, m) => s + m.missing.length, 0);
  const completeness: MonitoringCompleteness = {
    recordedFields,
    expectedFields,
    percent: expectedFields === 0 ? 0 : Math.round((recordedFields / expectedFields) * 100),
    missingByVisit,
  };

  /* --------------------------------------------- per-visit completeness */

  const visitCompleteness: VisitCompleteness[] = visits.map((v) => {
    const checks = [
      {
        label: "Ultrasound complete",
        ok:
          v.follicleCount !== null &&
          v.largestFollicle !== null &&
          v.follicles10 !== null &&
          v.endometrium !== null,
      },
      { label: "E2 available", ok: v.estradiol !== null },
      { label: "LH available", ok: v.lh !== null },
      { label: "P4 available", ok: v.progesterone !== null },
      { label: "Dose recorded", ok: v.dailyDose !== null },
      {
        label: "Medication changes recorded",
        ok: Boolean((v.medicationChange ?? "").trim()) || Boolean((v.medication ?? "").trim()),
      },
      { label: "Clinical assessment recorded", ok: Boolean((v.notes ?? "").trim()) || Boolean((v.symptoms ?? "").trim()) },
    ];
    const present = checks.filter((c) => c.ok).map((c) => c.label);
    const missing = checks.filter((c) => !c.ok).map((c) => c.label);
    const level: VisitCompletenessLevel =
      missing.length === 0 ? "COMPLETE" : present.length === 0 ? "INCOMPLETE" : "PARTIALLY COMPLETE";
    return { visitId: v.id, day: v.day, level, present, missing, checks };
  });

  /* ------------------------------------------------------------ validation */

  const validation: MonitoringValidationIssue[] = [];
  const invalid = (day: number | null, field: string, message: string) =>
    validation.push({ id: `${field}-${day ?? "x"}-${validation.length}`, day, severity: "invalid", field, message });
  const conflict = (day: number | null, field: string, message: string) =>
    validation.push({ id: `${field}-${day ?? "x"}-${validation.length}`, day, severity: "conflict", field, message });

  const seenDays = new Set<number>();
  for (const v of visits) {
    if (!Number.isFinite(v.day) || v.day < 1) invalid(v.day, "Stimulation day", "A stimulation day cannot precede day 1.");
    if (seenDays.has(v.day)) conflict(v.day, "Stimulation day", `More than one visit is recorded for day ${v.day}.`);
    seenDays.add(v.day);

    if (v.dailyDose !== null && v.dailyDose < 0) invalid(v.day, "Daily dose", "Dose cannot be negative.");
    for (const [label, value] of [
      ["Largest follicle", v.largestFollicle],
      ["Endometrial thickness", v.endometrium],
      ["Estradiol", v.estradiol],
      ["LH", v.lh],
      ["Progesterone", v.progesterone],
      ["Follicle count", v.follicleCount],
    ] as [string, number | null][]) {
      if (value !== null && value < 0) invalid(v.day, label, `${label} cannot be negative.`);
    }
    if (v.follicleSizes.some((x) => x <= 0)) invalid(v.day, "Follicle sizes", "A follicle diameter must be greater than zero.");

    if (v.follicles14 !== null && v.follicles10 !== null && v.follicles14 > v.follicles10)
      conflict(v.day, "Follicle bands", "Follicles ≥ 14 mm exceed follicles ≥ 10 mm.");
    if (v.follicles17 !== null && v.follicles14 !== null && v.follicles17 > v.follicles14)
      conflict(v.day, "Follicle bands", "Follicles ≥ 17 mm exceed follicles ≥ 14 mm.");
    if (v.follicleCount !== null && v.follicles10 !== null && v.follicles10 > v.follicleCount)
      conflict(v.day, "Follicle count", "Follicles ≥ 10 mm exceed the total follicle count.");
    if (v.largestFollicle !== null && v.follicleSizes.length && v.largestFollicle < Math.max(...v.follicleSizes))
      conflict(v.day, "Largest follicle", "An individual measurement is larger than the recorded lead follicle.");
    const sideSum = (v.rightFollicles ?? null) !== null && (v.leftFollicles ?? null) !== null
      ? (v.rightFollicles as number) + (v.leftFollicles as number)
      : null;
    if (sideSum !== null && v.follicleCount !== null && sideSum !== v.follicleCount)
      conflict(v.day, "Follicles by ovary", `Right + left (${sideSum}) does not equal the total follicle count (${v.follicleCount}).`);
    if (v.carriedForward) {
      validation.push({
        id: `carried-${v.day}`,
        day: v.day,
        severity: "missing",
        field: "Carried forward value",
        message: `Carried forward historical value: ${v.carriedForward}. Not a measurement taken on day ${v.day}.`,
      });
    }
  }

  /* ---------------------------------------------------------- dose timeline */

  const doseTimeline: DoseTimelineEntry[] = [];
  let lastDose: number | null = null;
  let lastMedication = "";
  for (const v of visits) {
    const dose = v.dailyDose;
    let change = "Not recorded";
    if (dose !== null) {
      if (lastDose === null) change = doseTimeline.length === 0 ? "First recorded dose" : "Dose recorded";
      else if (dose > lastDose) change = `Increased by ${round(dose - lastDose, 2)} IU`;
      else if (dose < lastDose) change = `Decreased by ${round(lastDose - dose, 2)} IU`;
      else change = "No change";
    }
    const medicationChanged = Boolean(v.medication) && Boolean(lastMedication) && v.medication !== lastMedication;
    doseTimeline.push({
      id: v.id,
      day: v.day,
      dose: dose === null ? "Not recorded" : `${dose} IU/day`,
      medication: v.medication || "Not recorded",
      change: medicationChanged ? `${change} · medication changed from ${lastMedication}` : change,
      reason: v.doseChangeReason?.trim() || v.medicationChange?.trim() || "No reason recorded",
      source: "Physician-entered visit record",
      physicianDecision: "PHYSICIAN-ENTERED",
    });
    if (dose !== null) lastDose = dose;
    if (v.medication) lastMedication = v.medication;
  }

  /* -------------------------------------------------- follicle trajectories */

  const trajectoryMap = new Map<string, FollicleTrajectory>();
  for (const v of visits) {
    for (const f of v.follicleRecords ?? []) {
      if (!f.followId) continue;
      const key = `${f.side}-${f.followId}`;
      const existing = trajectoryMap.get(key);
      if (existing) existing.points.push({ day: v.day, size: f.size });
      else
        trajectoryMap.set(key, {
          followId: f.followId,
          side: f.side,
          points: [{ day: v.day, size: f.size }],
          baseline: null,
          current: null,
          change: "—",
        });
    }
  }
  const follicleTrajectories = [...trajectoryMap.values()].map((t) => {
    t.points.sort((a, b) => a.day - b.day);
    const baseline = t.points[0]?.size ?? null;
    const current = t.points[t.points.length - 1]?.size ?? null;
    return {
      ...t,
      baseline,
      current,
      change:
        baseline === null || current === null || t.points.length < 2
          ? "Single measurement"
          : `${current - baseline > 0 ? "+" : ""}${round(current - baseline, 2)} mm since day ${t.points[0]!.day}`,
    };
  });

  /* -------------------------------------------------------------- alerts */

  const alerts: MonitoringAlert[] = [];
  const push = (a: MonitoringAlert) => alerts.push(a);

  const leadTrend = trends.find((t) => t.id === "largest")!;
  const leadPoints = visits
    .map((v) => ({ day: v.day, value: v.largestFollicle }))
    .filter((p): p is { day: number; value: number } => p.value !== null);

  if (leadPoints.length >= 2) {
    const a = leadPoints[leadPoints.length - 2]!;
    const b = leadPoints[leadPoints.length - 1]!;
    const perDay = round((b.value - a.value) / Math.max(1, b.day - a.day), 2);
    if (perDay >= descriptiveBands.leadGrowthRapidMmPerDay) {
      push({
        id: "rapid-growth",
        kind: "rapid-growth",
        label: monitoringAlertLabel["rapid-growth"],
        observation: `Lead follicle increased ${perDay} mm/day between day ${a.day} and day ${b.day}.`,
        basis: `Descriptive band ≥ ${descriptiveBands.leadGrowthRapidMmPerDay} mm/day. ${DESCRIPTIVE_BAND_DISCLAIMER}`,
      });
    } else if (perDay <= descriptiveBands.leadGrowthSlowMmPerDay) {
      push({
        id: "slow-growth",
        kind: "slow-growth",
        label: monitoringAlertLabel["slow-growth"],
        observation: `Lead follicle changed ${perDay} mm/day between day ${a.day} and day ${b.day}.`,
        basis: `Descriptive band ≤ ${descriptiveBands.leadGrowthSlowMmPerDay} mm/day. ${DESCRIPTIVE_BAND_DISCLAIMER}`,
      });
    }
  }

  const latest = visits[visits.length - 1];
  if (latest && latest.follicles10 !== null) {
    if (latest.follicles10 >= descriptiveBands.excessiveFollicles10) {
      push({
        id: "excessive",
        kind: "possible-excessive-response",
        label: monitoringAlertLabel["possible-excessive-response"],
        observation: `${latest.follicles10} follicles ≥ 10 mm recorded on stimulation day ${latest.day}.`,
        basis: `Descriptive band ≥ ${descriptiveBands.excessiveFollicles10} follicles. ${DESCRIPTIVE_BAND_DISCLAIMER} No OHSS threshold is activated.`,
      });
    } else if (latest.follicles10 <= descriptiveBands.inadequateFollicles10) {
      push({
        id: "inadequate",
        kind: "possible-inadequate-response",
        label: monitoringAlertLabel["possible-inadequate-response"],
        observation: `${latest.follicles10} follicles ≥ 10 mm recorded on stimulation day ${latest.day}.`,
        basis: `Descriptive band ≤ ${descriptiveBands.inadequateFollicles10} follicles. ${DESCRIPTIVE_BAND_DISCLAIMER}`,
      });
    }
  }

  const incomplete = missingByVisit.filter((m) => m.missing.length > 0);
  if (incomplete.length) {
    push({
      id: "incomplete",
      kind: "incomplete-monitoring",
      label: monitoringAlertLabel["incomplete-monitoring"],
      observation: `${incomplete.length} visit(s) have unrecorded monitoring fields: ${incomplete
        .map((m) => `day ${m.day} (${m.missing.length})`)
        .join(", ")}.`,
      basis: `Data completeness check on the entered visits. ${DESCRIPTIVE_ONLY_NOTICE}`,
    });
  }

  const missingLabs = visits.filter((v) => v.estradiol === null).map((v) => v.day);
  if (missingLabs.length) {
    push({
      id: "missing-labs",
      kind: "missing-laboratory",
      label: monitoringAlertLabel["missing-laboratory"],
      observation: `Estradiol not recorded on stimulation day(s) ${missingLabs.join(", ")}.`,
      basis: `Data completeness check on the entered visits. ${DESCRIPTIVE_ONLY_NOTICE}`,
    });
  }

  /* -------------------------------------------------------------- status */

  let status: MonitoringStatus = "no-data";
  let statusDetail = "Add the first monitoring visit to start the stimulation timeline.";

  if (visits.length === 1) {
    status = "assessment-pending";
    statusDetail =
      "A single visit is recorded. A trend requires at least two measurements of the same parameter.";
  } else if (visits.length >= 2) {
    if (incomplete.length > 0 || missingLabs.length > 0) {
      status = "additional-monitoring-required";
      statusDetail =
        "Some monitoring fields are unrecorded. Complete the visit data so the trend view reflects the whole cycle.";
    } else if (leadTrend.direction === "rising") {
      status = "appears-stable";
      statusDetail =
        "Follicular measurements are increasing across the recorded visits and all monitored fields are documented. This is a description of the entered data, not a clinical judgement.";
    } else {
      status = "assessment-pending";
      statusDetail =
        "Recorded measurements do not show a consistent direction. Review with the next scan.";
    }
  }

  /* ------------------------------------------------------------- summary */

  const hormoneParts = latest
    ? [
        latest.estradiol === null ? null : `E2 ${latest.estradiol} pg/mL`,
        latest.progesterone === null ? null : `P4 ${latest.progesterone} ng/mL`,
        latest.lh === null ? null : `LH ${latest.lh} IU/L`,
      ].filter(Boolean)
    : [];

  /* -------------------------------------------------- expected vs observed */

  const observedParts = latest
    ? [
        latest.follicleCount === null ? null : `${latest.follicleCount} follicles`,
        latest.follicles10 === null ? null : `${latest.follicles10} ≥ 10 mm`,
        latest.estradiol === null ? null : `E2 ${latest.estradiol} pg/mL`,
      ].filter(Boolean)
    : [];

  const expectedVsObserved: ExpectedVsObserved = {
    expected: context.expectedResponse.expected,
    expectedSource: context.expectedResponse.source,
    observed: observedParts.length
      ? `Stimulation day ${latest!.day}: ${observedParts.join(" · ")}`
      : "No observed measurement recorded",
    difference: observedParts.length
      ? "The observed values above are stated as measured. No numeric expected follicle count exists in the Evidence Library, so no arithmetic difference is computed."
      : "Not computable — no observed measurement.",
    evidenceStatus: context.expectedResponse.evidenceStatus,
  };

  /* --------------------------------------------- descriptive response phenotype */

  const descriptor = (id: string, label: string, t: MonitoringTrend | undefined): ResponseDescriptor | null => {
    if (!t || t.direction === "unknown") return null;
    const word =
      t.direction === "rising" ? "increasing" : t.direction === "falling" ? "decreasing" : "stable";
    return {
      id,
      label: `${label} ${word}`,
      detail: `Latest ${t.latest}; previous ${t.previous}; change ${t.change} (${t.perDay}).`,
    };
  };

  const descriptors = [
    descriptor("cohort", "Follicular cohort", trends.find((t) => t.id === "f10")),
    descriptor("lead", "Lead follicle", trends.find((t) => t.id === "largest")),
    descriptor("e2", "Estradiol", trends.find((t) => t.id === "e2")),
    descriptor("lh", "LH", trends.find((t) => t.id === "lh")),
    descriptor("p4", "Progesterone", trends.find((t) => t.id === "p4")),
    descriptor("endometrium", "Endometrium", trends.find((t) => t.id === "endometrium")),
  ].filter((d): d is ResponseDescriptor => d !== null);

  const summary: MonitoringSummary = {
    currentDay: latest ? latest.day : null,
    currentDose: latest
      ? `${fmt(latest.dailyDose, "IU/day")} (entered by the clinician — not a recommendation)`
      : "Not recorded",

    follicularDevelopment: latest
      ? [
          latest.follicleCount === null ? null : `${latest.follicleCount} follicles seen`,
          latest.largestFollicle === null ? null : `largest ${latest.largestFollicle} mm`,
          latest.follicles10 === null ? null : `${latest.follicles10} ≥ 10 mm`,
          latest.follicles14 === null ? null : `${latest.follicles14} ≥ 14 mm`,
          latest.follicles17 === null ? null : `${latest.follicles17} ≥ 17 mm`,
        ]
          .filter(Boolean)
          .join(" · ") || "Not recorded"
      : "Not recorded",
    hormoneResults: hormoneParts.length ? hormoneParts.join(" · ") : "Not recorded",
    responseTrend:
      leadTrend.direction === "unknown"
        ? "Insufficient measurements for a trend."
        : `Largest follicle ${leadTrend.change} since the previous scan (${leadTrend.perDay}).`,
    completeness: `${completeness.percent}% of monitored fields recorded (${completeness.recordedFields}/${completeness.expectedFields}).`,
    pendingRecommendations: MONITORING_PENDING_MESSAGE,
  };

  return {
    patientId: context.patientId,
    patientName: context.patientName,
    context,
    visits,
    series,
    trends,
    alerts,
    status,
    statusDetail,
    completeness,
    visitCompleteness,
    validation,
    doseTimeline,
    follicleTrajectories,
    expectedVsObserved,
    descriptors,
    summary,
    pendingMessage: MONITORING_PENDING_MESSAGE,
    evidenceSource: monitoringEvidenceIds,
    computedAt: new Date().toISOString(),
    version: MONITORING_ENGINE_VERSION,
  };
}

