/**
 * Defensive normalisation of a stored visit.
 *
 * Visits persisted by an earlier build can be missing fields that were added
 * later (notably `follicleSizes`). Reading such a record used to throw and
 * take the whole monitoring/trigger/report chain down. Missing fields are
 * restored to their EMPTY defaults only — no measurement is ever invented.
 */
export function normalizeVisit(visit: MonitoringVisit): MonitoringVisit {
  const raw = (visit ?? {}) as Partial<MonitoringVisit>;
  const day = typeof raw.day === "number" && Number.isFinite(raw.day) ? raw.day : 0;
  const sizes = Array.isArray(raw.follicleSizes)
    ? raw.follicleSizes.filter((n): n is number => typeof n === "number" && Number.isFinite(n))
    : [];
  return {
    ...emptyVisit(day),
    ...raw,
    id: raw.id ?? `visit-${day}`,
    recordedAt: raw.recordedAt ?? "",
    day,
    follicleSizes: sizes,
    follicleRecords: Array.isArray(raw.follicleRecords) ? raw.follicleRecords : [],
  };
}

