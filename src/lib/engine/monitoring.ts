/* ------------------------------------------------------------------ report */

export function monitoringReportText(r: MonitoringResult): string {
  const lines: string[] = [
    "MONITORING REPORT — Dynamic Ovarian Stimulation Monitoring",
    `Patient: ${r.patientName}`,
    `Generated: ${new Date(r.computedAt).toISOString().slice(0, 10)}`,
    `Engine version: ${r.version}`,
    "",
    "CYCLE CONTEXT",
    ...r.context.items.map((i) => `  ${i.label}: ${i.value}`),
    "",
    "TIMELINE / DAILY DOSE HISTORY",
  ];

  if (!r.visits.length) lines.push("  No monitoring visit recorded.");
  for (const v of r.visits) {
    lines.push(
      `  Day ${v.day}${v.triggerDay ? " (trigger day)" : ""}${v.date ? ` — ${v.date}` : ""}`,
    );
    lines.push(`    Dose: ${fmt(v.dailyDose, "IU/day")}${v.medication ? ` · ${v.medication}` : ""}`);
    if (v.medicationChange) lines.push(`    Medication change: ${v.medicationChange}`);
    lines.push(
      `    Ultrasound: ${fmt(v.follicleCount, "follicles")} · largest ${fmt(v.largestFollicle, "mm")} · ≥10mm ${fmt(v.follicles10)} · ≥14mm ${fmt(v.follicles14)} · ≥17mm ${fmt(v.follicles17)} · endometrium ${fmt(v.endometrium, "mm")}`,
    );
    if (v.follicleSizes.length) lines.push(`    Follicle sizes: ${v.follicleSizes.join(", ")} mm`);
    lines.push(
      `    Hormones: E2 ${fmt(v.estradiol, "pg/mL")} · P4 ${fmt(v.progesterone, "ng/mL")} · LH ${fmt(v.lh, "IU/L")}`,
    );
    if (v.notes) lines.push(`    Notes: ${v.notes}`);
  }

  lines.push(
    "",
    "RESPONSE TREND",
    ...r.trends.map((t) => `  ${t.label}: latest ${t.latest} · previous ${t.previous} · ${t.perDay}`),
    "",
    `MONITORING STATUS: ${monitoringStatusLabel[r.status]}`,
    `  ${r.statusDetail}`,
    "",
    "INFORMATIONAL ALERTS",
  );
  if (!r.alerts.length) lines.push("  None.");
  for (const a of r.alerts) lines.push(`  ${a.label}: ${a.observation} (${a.basis})`);

  lines.push(
    "",
    "DOSE TIMELINE",
    ...(r.doseTimeline.length
      ? r.doseTimeline.map(
          (d) => `  Day ${d.day} — ${d.dose} — ${d.medication} — ${d.change} — ${d.physicianDecision}`,
        )
      : ["  No dose recorded."]),
    "",
    "EXPECTED VS OBSERVED",
    `  Expected: ${r.expectedVsObserved.expected} (${r.expectedVsObserved.expectedSource})`,
    `  Observed: ${r.expectedVsObserved.observed}`,
    `  Difference: ${r.expectedVsObserved.difference}`,
    "",
    "DATA VALIDATION",
    ...(r.validation.length
      ? r.validation.map((v) => `  [${v.severity}] Day ${v.day ?? "?"} · ${v.field}: ${v.message}`)
      : ["  No validation issue detected."]),
    "",
    "PREVIOUS CYCLES (immutable historical records)",
    ...(r.context.previousCycles.length
      ? r.context.previousCycles.map(
          (c) =>
            `  ${c.label}: ${c.protocol} · ${c.gonadotropin} · start ${c.startingDose} · max ${c.maximumDose} · ${c.duration} · retrieved ${c.retrieved} · MII ${c.mii} · ${c.embryology} · ${c.pregnancy} · OHSS ${c.ohss}`,
        )
      : ["  No previous cycle recorded."]),
    "",
    "MONITORING COMPLETENESS",
    `  ${r.summary.completeness}`,
    "",
    "PENDING EVIDENCE-BASED RECOMMENDATIONS",
    `  ${r.pendingMessage}`,
    "",
    "EVIDENCE REFERENCES",
    ...r.evidenceSource.map((id) => `  ${id}`),
    "",
    "REQUIRED TO ACTIVATE DOSE ADJUSTMENT",
    ...MONITORING_REQUIRED_EVIDENCE.map((x) => `  - ${x}`),
  );

  return lines.join("\n");
}
