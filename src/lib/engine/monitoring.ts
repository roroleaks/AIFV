const fmt = (v: number | null, unit = "") =>
  v === null ? "Not recorded" : `${v}${unit ? ` ${unit}` : ""}`;

export function buildMonitoringContext(
  patientId: string,
  patientName: string,
  _values: Record<string, FieldValue>,
  cycles: CycleRecord[],
  phenotype: PhenotypeResult,
  response: OvarianResponseResult,
  protocol: ProtocolRecommendationResult,
  gonadotropin: GonadotropinSelectionResult,
  consort: StoredConsortDose | null,
): MonitoringContext {
  const s = phenotype.patientSummary;
  const majorRisks = response.risks.filter((r) => r.severity !== "info").map((r) => r.label);
  const ohssRisks = response.risks
    .filter((r) => r.label.toLowerCase().includes("ohss") || r.label.toLowerCase().includes("hyper"))
    .map((r) => r.label);

  const items: MonitoringContextItem[] = [
    {
      id: "demographics",
      label: "Patient demographics",
      value: [s.age === null ? null : `${s.age} years`, s.bmi === null ? null : `BMI ${s.bmi}`]
        .filter(Boolean)
        .join(" · ") || "Not recorded",
      available: s.age !== null || s.bmi !== null,
    },
    {
      id: "diagnosis",
      label: "Diagnosis",
      value: s.diagnosis.length ? s.diagnosis.join(", ") : "Not recorded",
      available: s.diagnosis.length > 0,
    },
    {
      id: "protocol",
      label: "Protocol",
      value: gatedTreatmentValue("protocol-recommendation", protocol.recommendation.recommended)
        ? String(protocol.recommendation.recommended)
        : "Protocol recommendation algorithm: Evidence Pending",
      available: false,
      detail: protocol.recommendation.message,
    },
    {
      id: "gonadotropin",
      label: "Gonadotropin",
      value: gatedTreatmentValue("gonadotropin-selection", gonadotropin.selection.recommended)
        ? String(gonadotropin.selection.recommended)
        : "Gonadotropin selection algorithm: Evidence Pending",
      available: false,
      detail: gonadotropin.selection.message,
    },
    {
      id: "starting-dose",
      label: "Starting dose",
      value:
        gatedTreatmentValue("consort-dose", consort && consort.dose !== null ? consort.dose : null) !==
        null
          ? `${consort!.dose} IU/day (${consort!.medication})`
          : "CONSORT dose calculation unavailable — validated methodology not activated",
      available: false,
    },

    {
      id: "poseidon",
      label: "POSEIDON group",
      value: phenotype.poseidon.groupLabel ?? "Not classified",
      available: true,
    },

    {
      id: "bologna",
      label: "Bologna status",
      value: phenotype.bologna.headline,
      available: true,
    },
    {
      id: "expected-response",
      label: "Expected ovarian response",
      value: responseCategoryLabel[response.category],
      available: response.category !== "unable",
    },
    {
      id: "previous-cycles",
      label: "Previous cycle history",
      value: cycles.length ? `${cycles.length} recorded cycle(s)` : "No previous cycle recorded",
      available: cycles.length > 0,
    },
    {
      id: "ohss-risk",
      label: "OHSS risk",
      value: ohssRisks.length
        ? ohssRisks.join(" · ")
        : majorRisks.length
          ? `No OHSS-specific marker · other risks: ${majorRisks.join(", ")}`
          : "No documented OHSS risk marker",
      available: true,
      detail: "Risk markers only. OHSS Risk Engine thresholds are not activated.",
    },
  ];

  const text = (c: CycleRecord, key: string, unit = "") => {
    const raw = c[key];
    if (raw === undefined || raw === null || raw === "") return "Not recorded";
    return `${String(raw)}${unit ? ` ${unit}` : ""}`;
  };

  const previousCycles: PreviousCycleRow[] = cycles.map((c, i) => ({
    id: c.id,
    label: `Cycle ${c["cycleNumber"] ?? i + 1}${c["cycleYear"] ? ` (${c["cycleYear"]})` : ""}`,
    protocol: text(c, "protocol"),
    gonadotropin: [text(c, "gonadotropinType"), c["medication"] ? String(c["medication"]) : null]
      .filter((x) => x && x !== "Not recorded")
      .join(" · ") || "Not recorded",
    startingDose: text(c, "startingDose", "IU/day"),
    maximumDose: text(c, "maxDose", "IU/day"),
    duration: text(c, "duration", "days"),
    retrieved: text(c, "retrieved"),
    mii: text(c, "mii"),
    embryology: [
      c["twoPn"] === undefined || c["twoPn"] === "" ? null : `2PN ${c["twoPn"]}`,
      c["blastocysts"] === undefined || c["blastocysts"] === "" ? null : `Blastocysts ${c["blastocysts"]}`,
      c["frozen"] === undefined || c["frozen"] === "" ? null : `Frozen ${c["frozen"]}`,
    ]
      .filter(Boolean)
      .join(" · ") || "Not recorded",
    pregnancy: [
      c["clinicalPregnancy"] ? `Clinical pregnancy ${c["clinicalPregnancy"]}` : null,
      c["liveBirth"] ? `Live birth ${c["liveBirth"]}` : null,
    ]
      .filter(Boolean)
      .join(" · ") || "Not recorded",
    ohss: text(c, "ohss"),
  }));

  const protocolItem = items.find((i) => i.id === "protocol")!;
  const gonadotropinItem = items.find((i) => i.id === "gonadotropin")!;

  return {
    patientId,
    patientName,
    items,
    previousCycles,
    expectedResponse: {
      expected: responseCategoryLabel[response.category],
      source: "Ovarian Response Prediction Engine (descriptive phenotype, no dose output)",
      evidenceStatus:
        "Descriptive prediction. Any difference from the observed response is arithmetic only and does not imply under- or over-response.",
      available: response.category !== "unable",
    },
    currentProtocol: protocolItem.value,
    currentGonadotropin: gonadotropinItem.value,
    safetyMarkers: ohssRisks.length ? ohssRisks : majorRisks,
  };
}

